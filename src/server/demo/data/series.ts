/**
 * Demo auction series. Each series runs recurring auction instances on a fixed wall-clock
 * schedule (cycle), so every server instance derives the same live auctions from the same time.
 *
 *   cycleStart ── lead ──► startsAt ── open (initial countdown) ──► closing phase ──► completed
 */
export interface AuctionSeries {
  key: string
  products: string[]
  cycleMinutes: number
  offsetMinutes: number
  leadMinutes: number
  openMinutes: number
  /** 0–1: how competitive the simulated bidding is. */
  heat: number
  /** Expected length of the closing phase (final-seconds bidding), in minutes. */
  closingMinutes: number
  incrementMinor: number
  bidCreditCost: number
  extensionSeconds: number
  featured?: boolean
  maxPreviousWins?: number
  minimumTier?: RewardTier
  reserveBps?: number
  minimumParticipants?: number
  recovery?: { enabled: boolean; mode?: RecoveryMode }
  autoBid?: boolean
  perUserBidLimit?: number
  hardStopMinutes?: number
  label?: string
}

