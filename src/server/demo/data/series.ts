/** Wall-clock anchor for the demo schedule. */
export const DEMO_EPOCH = Date.UTC(2026, 0, 1)

export function seriesRules(
  series: AuctionSeries,
  referencePriceMinor: number,
): Partial<AuctionRules> {
  return {
    startingPriceMinor: 0,
    bidIncrementMinor: series.incrementMinor,
    bidCreditCost: series.bidCreditCost,
    timerSeconds: series.openMinutes * 60,
    timerExtensionSeconds: series.extensionSeconds,
    minimumParticipants: series.minimumParticipants ?? 2,
    hardStopAfterSeconds: series.hardStopMinutes ? series.hardStopMinutes * 60 : null,
    buyNowEnabled: true,
    bidCreditRecoveryEnabled: series.recovery?.enabled ?? true,
    recoveryMode: series.recovery?.mode ?? 'RETURN_BIDS',
    reservePriceMinor: series.reserveBps
      ? Math.round((referencePriceMinor * series.reserveBps) / 10_000)
      : null,
    perUserBidLimit: series.perUserBidLimit ?? null,
    autoBidEnabled: series.autoBid ?? true,
    eligibility: {
      minimumTier: series.minimumTier ?? null,
      maxPreviousWins: series.maxPreviousWins ?? null,
      minimumAccountAgeDays: null,
      markets: ['UK'],
      minimumAge: 18,
    },
  }
}
