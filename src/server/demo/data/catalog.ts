export const PRODUCT_EPOCH = Date.UTC(2026, 0, 5)

export function buildProducts(anchorDay: number): Product[] {
  const brandNames = new Map(BRANDS.map((brand) => [brand.slug, brand.name]))
  return SEEDS.map((seed, index) => {
    const [body, shade, accent, backdrop] = seed.palette
    const palette: ArtPalette = { body, shade, accent, backdrop }
    const createdAt = anchorDay - ((index * 7) % 120) * DAY - (index % 5) * 3_600_000
    return {
      id: deterministicUuid('product', seed.slug),
      slug: seed.slug,
      sku: `ESB-${CATEGORY_CODE[seed.category] ?? 'GEN'}-${String(index + 101).padStart(4, '0')}`,
      name: seed.name,
      brandSlug: seed.brand,
      brandName: brandNames.get(seed.brand) ?? seed.brand,
      description: seed.description,
      highlights: seed.highlights,
      categorySlug: seed.category,
      subcategory: seed.subcategory,
      images: [0, 1, 2].map((variant) => ({
        alt: `${seed.name} — ${['front view', 'detail view', 'angled view'][variant]}`,
        art: seed.art,
        variant,
      })),
      palette,
      colourway: seed.colourway,
      currency: 'GBP' as const,
      referencePriceMinor: seed.ref,
      buyNowPriceMinor: seed.buyNow,
      costPriceMinor: seed.cost,
      supplierId: supplierFor[seed.category] ?? SUPPLIERS[0]!.id,
      condition: seed.condition ?? 'NEW',
      shippingClass: seed.shipping,
      attributes: { Colour: seed.colourway, ...seed.attributes },
      status: 'ACTIVE' as const,
      auctionEligible: seed.auction ?? (seed.shipping !== 'DIGITAL' || seed.ref >= 5_000),
      tags: seed.tags,
      popularity: seed.popularity,
      rating: seed.rating,
      reviewCount: seed.reviews,
      createdAt,
      updatedAt: createdAt,
    }
  })
}

export function initialStock(slug: string): number {
  return SEEDS.find((seed) => seed.slug === slug)?.stock ?? 0
}

